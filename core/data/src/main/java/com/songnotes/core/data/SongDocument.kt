/**
 * The song document: the plaintext JSON both apps encrypt into a row's
 * `content` (docs/WIRE-FORMAT-v2.md section 4). One writer and one reader, the
 * Kotlin twin of the web app's `src/store/songDocument.js`
 * (`songToDocument`/`songFromDocument`), and checked against the same cases:
 * `spec/song-documents.json`, generated by the web repo, run here by
 * `SongDocumentGoldenFixtureTest`.
 *
 * The reader matches the web's exactly, including the legacy shapes still
 * found in old web rows -- a line's `chords` as v1's padded string, a line
 * with no `id`, `bpm`/`capo` as strings. It used to throw on the first two,
 * and `SyncEngine.pull` skipped the row, so those songs silently never
 * reached this device while the web app showed them fine.
 */

/** The document for [song], exactly as it's encrypted. */
internal fun songToDocument(song: Song): JSONObject {
    val doc = JSONObject()
        .put("title", song.title)
        .put("lines", linesToJson(song.lines))
        .put("bpm", song.meta.bpm)
        .put("key", song.meta.key)
        .put("tuning", song.meta.tuning)
        .put("capo", song.meta.capo)
        .put("createdAt", toIso(song.createdAt))
        .put("updatedAt", toIso(song.updatedAt))
    if (song.customChords.isNotEmpty()) doc.put("customChords", customChordsToJson(song.customChords))
    stampsToJson(song.fieldEditedAt.filterKeys { it in STAMPED_FIELDS })?.let { doc.put("fieldEditedAt", it) }
    stampsToJson(song.customChordsEditedAt)?.let { doc.put("customChordsEditedAt", it) }
    return doc
}

/** Valid edit stamps as a JSON object, or null when there are none (src/sync/editStamps.js on the web). */
private fun stampsToJson(stamps: Map<String, Long>): JSONObject? {
    val valid = stamps.filterValues { validStamp(it) != null }
    if (valid.isEmpty()) return null
    val obj = JSONObject()
    for ((key, stamp) in valid.toSortedMap()) obj.put(key, stamp)
    return obj
}

/**
 * A stamp as read from JSON: a whole number of ms from 0 to 2^53 - 1 (the
 * web's Number.isSafeInteger check), else null -- a fraction, a string or a
 * negative number reads as no stamp at all.
 */
private fun stampFromJson(value: Any?): Long? = when (value) {
    is Int -> validStamp(value.toLong())
    is Long -> validStamp(value)
    is Number -> value.toDouble().takeIf { it % 1.0 == 0.0 && it >= 0 && it <= 9_007_199_254_740_991.0 }?.toLong()
    else -> null
}

private fun stampsFromJson(json: JSONObject?, allowed: List<String>? = null): Map<String, Long> {
    if (json == null) return emptyMap()
    val result = sortedMapOf<String, Long>()
    for (key in json.keys()) {
        if (allowed != null && key !in allowed) continue
        stampFromJson(json.opt(key))?.let { result[key] = it }
    }
    return result
}

/**
 * The song for document [doc] stored under row id [id]. A line with no `id`
 * gets `legacy-<index>` (its 0-based position) -- the web reader's rule, and
 * stable across reads, so pulling the same row twice doesn't look like a
 * change; the song is saved under those ids the next time it's pushed. A
 * document missing `createdAt`/`updatedAt` falls back to the row's own
 * [rowCreatedAt]/[rowUpdatedAt] columns rather than "now", so it doesn't
 * jump to the top of the list on every pull.
 */
internal fun songFromDocument(id: String, doc: JSONObject, rowCreatedAt: String? = null, rowUpdatedAt: String? = null): Song {
    val linesJson = doc.optJSONArray("lines") ?: JSONArray()
    val lines = (0 until linesJson.length()).map { index ->
        val line = linesJson.getJSONObject(index)
        SongLine(
            id = stringOrNull(line, "id")?.takeIf { it.isNotEmpty() } ?: "legacy-$index",
            lyrics = stringOrNull(line, "lyrics") ?: "",
            chords = when (val chords = line.opt("chords")) {
                is JSONArray -> (0 until chords.length()).map { c ->
                    val anchor = chords.getJSONObject(c)
                    ChordAnchor(i = anchor.getInt("i"), c = anchor.getString("c"))
                }
                is String -> chordsLineToAnchors(chords)
                else -> emptyList()
            },
            editedAt = stampFromJson(line.opt("editedAt")),
        )
    }
    return Song(
        id = id,
        title = stringOrNull(doc, "title") ?: "",
        meta = SongMeta(
            bpm = toMetaNumber(doc.opt("bpm")),
            key = stringOrNull(doc, "key") ?: "",
            tuning = stringOrNull(doc, "tuning") ?: "",
            capo = toMetaNumber(doc.opt("capo")),
        ),
        lines = lines,
        customChords = customChordsFromJson(doc.optJSONObject("customChords")),
        createdAt = parseIso(stringOrNull(doc, "createdAt") ?: rowCreatedAt ?: error("song $id has no createdAt")),
        updatedAt = parseIso(stringOrNull(doc, "updatedAt") ?: rowUpdatedAt ?: error("song $id has no updatedAt")),
        fieldEditedAt = stampsFromJson(doc.optJSONObject("fieldEditedAt"), STAMPED_FIELDS),
        customChordsEditedAt = stampsFromJson(doc.optJSONObject("customChordsEditedAt")),
    )
}

/**
 * `bpm`/`capo` as a whole number, 0 meaning unset -- the web's `toMetaNumber`:
 * a number counts if it's positive (fractions floored); a string counts by
 * its leading digits, like JS `parseInt` ("92" and "92 bpm" are 92, "" is 0).
 * Anything else, or anything not above 0, is 0.
 */
internal fun toMetaNumber(value: Any?): Int {
    val n: Double = when (value) {
        is Number -> value.toDouble()
        is String -> Regex("""^[+-]?\d+""").find(value.trim())?.value?.toDoubleOrNull() ?: return 0
        else -> return 0
    }
    return if (n.isFinite() && n > 0) minOf(Math.floor(n), Int.MAX_VALUE.toDouble()).toInt() else 0
}

/** The string at [key], or null when it's absent or JSON `null` -- org.json's `optString` would turn a JSON `null` into the text "null". */
private fun stringOrNull(json: JSONObject, key: String): String? =
    if (!json.has(key) || json.isNull(key)) null else json.get(key).toString()

private fun linesToJson(lines: List<SongLine>): JSONArray {
    val arr = JSONArray()
    for (line in lines) {
        val chordsJson = JSONArray()
        for (chord in line.chords) chordsJson.put(JSONObject().put("i", chord.i).put("c", chord.c))
        val lineJson = JSONObject().put("id", line.id).put("lyrics", line.lyrics).put("chords", chordsJson)
        validStamp(line.editedAt)?.let { lineJson.put("editedAt", it) }
        arr.put(lineJson)
    }
    return arr
}

private fun customChordsToJson(customChords: Map<String, ChordVoicing>): JSONObject {
    val obj = JSONObject()
    for ((name, voicing) in customChords) {
        val voicingJson = JSONObject()
            .put("frets", JSONArray(voicing.frets))
            .put("baseFret", voicing.baseFret)
        voicing.barre?.let {
            voicingJson.put("barre", JSONObject().put("fret", it.fret).put("fromString", it.fromString).put("toString", it.toString))
        }
        obj.put(name, voicingJson)
    }
    return obj
}

private fun customChordsFromJson(json: JSONObject?): Map<String, ChordVoicing> {
    if (json == null) return emptyMap()
    val result = LinkedHashMap<String, ChordVoicing>()
    for (name in json.keys()) {
        val voicingJson = json.getJSONObject(name)
        val fretsJson = voicingJson.getJSONArray("frets")
        val frets = (0 until fretsJson.length()).map { fretsJson.getInt(it) }
        val barre = voicingJson.optJSONObject("barre")?.let {
            ChordBarre(fret = it.getInt("fret"), fromString = it.getInt("fromString"), toString = it.getInt("toString"))
        }
        result[name] = ChordVoicing(frets = frets, baseFret = voicingJson.getInt("baseFret"), barre = barre)
    }
    return result
}

internal fun toIso(epochMillis: Long): String = Instant.ofEpochMilli(epochMillis).toString()

// Postgrest returns timestamptz columns as "+00:00"-offset text (e.g.
// "2026-08-06T22:43:22.991+00:00"), not the "Z"-suffixed form toIso() writes --
// OffsetDateTime.parse's default ISO_OFFSET_DATE_TIME format accepts both.
internal fun parseIso(iso: String): Long = OffsetDateTime.parse(iso).toInstant().toEpochMilli()
